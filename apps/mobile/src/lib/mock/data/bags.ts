export function seedBags(base: Date): Bag[] {
  return seeds.map(({ window, ...seed }) => {
    const store = stores.find((s) => s.id === seed.storeId);
    return {
      ...seed,
      storeName: store?.name ?? "",
      storeAddress: store?.address ?? "",
      storeRating: store?.rating ?? 0,
      storeReviewCount: store?.reviewCount ?? 0,
      distanceKm: store?.distanceKm,
      pickupStart: vnTimeOn(base, window[0]),
      pickupEnd: vnTimeOn(base, window[1]),
    };
  });
}

